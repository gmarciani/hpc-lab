# First boot of a node: kubeadm configuration, then init on the control plane
# and join on every other node.
kubernetes = node['hpc-lab-kubernetes']

if ENV['KUBERNETES_TOKEN'].to_s.empty?
  raise "KUBERNETES_TOKEN is not set: #{kubernetes['home']}/kubernetes.secrets.env is kubernetes/.env.secrets.local, generated by `make start-kubernetes`"
end

execute "kubeadm is #{kubernetes['kubernetes_version']}" do
  command "kubeadm version -o short | grep -qxF '#{kubernetes['kubernetes_version']}'"
end

template '/etc/kubeadm.conf' do
  source 'kubeadm.conf.erb'
  variables(
    kubernetes_version: kubernetes['kubernetes_version'],
    cluster_name: kubernetes['cluster_name'],
    control_plane_host: kubernetes['control_plane_host'],
    api_port: kubernetes['api_port'],
    pod_subnet: kubernetes['pod_subnet'],
    service_subnet: kubernetes['service_subnet']
  )
end

# Cluster-wide scratch directory the Slurm pods mount, writable by everyone like /tmp.
directory '/shared' do
  mode '1777'
end

control_plane = node['hostname'] == kubernetes['control_plane_host']
include_recipe control_plane ? 'hpc-lab-kubernetes::control_plane' : 'hpc-lab-kubernetes::worker'
